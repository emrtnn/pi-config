"""Regenerate reference/api.md from the scripts' signatures and docstrings (run after extending the library).

usage: gen_api_doc.py            (writes <skill>/reference/api.md)
"""
import ast
import glob
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "reference", "api.md")
CLI = ("udsmesh_convert.py", "polyhaven_fetch.py", "blenderkit_fetch.py", "contact_sheet.py", "avz_render.py",
       "avz_bench.py", "gen_api_doc.py")


def sig(n):
    a = n.args
    args = [x.arg for x in a.args]
    defs = [ast.unparse(d) for d in a.defaults]
    s = args[:len(args) - len(defs)] + [f"{x}={d}" for x, d in zip(args[len(args) - len(defs):], defs)]
    if a.vararg:
        s.append("*" + a.vararg.arg)
    if a.kwonlyargs:
        if not a.vararg:
            s.append("*")
        s += [f"{k.arg}={ast.unparse(d)}" if d is not None else k.arg for k, d in zip(a.kwonlyargs, a.kw_defaults)]
    return ", ".join(s)


def main():
    L = ["# API reference (generated by scripts/gen_api_doc.py - do not edit by hand)", "",
         "## Blender modules (`import avz_*` after the SKILL.md bootstrap)", ""]
    for f in sorted(glob.glob(os.path.join(HERE, "avz_*.py"))):
        name = os.path.basename(f)
        if name in CLI:
            continue
        t = ast.parse(open(f).read())
        doc = (ast.get_docstring(t) or "").strip().splitlines()
        L += [f"### `{name[:-3]}` — {doc[0] if doc else ''}", ""]
        for n in t.body:
            if isinstance(n, ast.ClassDef) and not n.name.startswith("_"):
                L.append(f"- `class {n.name}` — {(ast.get_docstring(n) or '').splitlines()[0]}")
                for m in n.body:
                    if isinstance(m, ast.FunctionDef) and not m.name.startswith("_"):
                        L.append(f"  - `.{m.name}({sig(m).replace('self, ', '').replace('self', '').replace('cls, ', '')})`")
            elif isinstance(n, ast.FunctionDef) and not n.name.startswith(("_", "b_")):
                d = " ".join((ast.get_docstring(n) or "").split())
                L.append(f"- `{n.name}({sig(n)})`" + (f" — {d[:300]}" if d else ""))
        L.append("")
    L += ["## Command-line tools", ""]
    for name in CLI:
        p = os.path.join(HERE, name)
        if os.path.exists(p):
            L += [f"### `{name}`", "", "```", (ast.get_docstring(ast.parse(open(p).read())) or "").strip(), "```", ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(L))
    print(OUT)


if __name__ == "__main__":
    main()
